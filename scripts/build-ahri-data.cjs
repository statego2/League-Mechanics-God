// Generate the browser snapshot from the reviewed PR #1 records, never historical data.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const snapshot = JSON.parse(fs.readFileSync(path.join(root, 'data/ahri-snapshot.json'), 'utf8'));
if (snapshot.version !== '16.21.1') throw Error('Unexpected Ahri roster version; review the adapter first');
function value(section, key, unit) {
  const entry = snapshot[section]?.[key];
  if (!entry || entry.patch !== snapshot.version || entry.status !== 'direct' || entry.unit !== unit || typeof entry.value !== 'number' || !Number.isFinite(entry.value) || entry.value <= 0) throw Error(`Invalid ${section}.${key}`);
  return entry.value;
}
const roster = (key, unit = 'riot_stat_units') => value('roster', key, unit);
const featured = (key, unit) => value('featured', key, unit);
const data = {
  patch: snapshot.version, sourceId: 'riot-roster+featured-pr1',
  base: {hp: roster('hp'), moveSpeed: roster('movespeed', 'game_units_per_second'), attackRange: roster('attackrange', 'game_units'), attackSpeed: roster('attackspeed', 'attacks_per_second'), attackDamage: roster('attackdamage')},
  attack: {windupFraction: featured('attack_windup_percent', 'percent') / 100, missileSpeed: featured('attack_missile_speed', 'game_units_per_second')},
  q: {cast: featured('q_cast_time', 'seconds'), range: featured('q_range', 'game_units'), speed: featured('q_outbound_speed', 'game_units_per_second'), width: featured('q_width', 'game_units')},
  gameplayRadius: 65
};
const output = `// Generated by scripts/build-ahri-data.cjs; do not edit. Radius is a community-reported approximation.\nwindow.LMGAhriData = ${JSON.stringify(data, null, 2)};\n`;
const target = path.join(root, 'ahri-data.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) { console.error('ahri-data.js is stale'); process.exitCode = 1; }
} else fs.writeFileSync(target, output);
